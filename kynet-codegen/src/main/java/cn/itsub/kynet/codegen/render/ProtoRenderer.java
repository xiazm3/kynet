package cn.itsub.kynet.codegen.render;

import cn.itsub.kynet.codegen.ir.ActionMeta;
import cn.itsub.kynet.codegen.ir.EnumMeta;
import cn.itsub.kynet.codegen.ir.FieldMeta;
import cn.itsub.kynet.codegen.ir.IrModel;
import cn.itsub.kynet.codegen.ir.MessageMeta;
import cn.itsub.kynet.codegen.ir.TypeKind;
import cn.itsub.kynet.codegen.ir.TypeRef;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.HashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * 生成一个 .proto 文件：消息字段号与 jprotobuf order 一致；action 以 service/rpc 表达。
 * 非 protobuf 标准的 kynet 载荷（裸字符串、PrimitiveValue 信封、List 信封）用具名消息 +
 * wire 注释如实标注，供文档与第三方工具使用。
 */
public final class ProtoRenderer implements Renderer {
    public static final String OUTPUT = "kynet-actions.proto";

    @Override
    public List<Path> render(IrModel model, RenderOptions options, Path outDir) throws IOException {
        StringBuilder out = new StringBuilder();
        Set<TypeKind> envelopeUsage = new LinkedHashSet<>();
        boolean needsEmpty = model.actions().stream().anyMatch(action -> action.returnType() == null);
        boolean needsWrappers = needsEmpty;

        out.append("// Generated by kynet-codegen at ").append(options.generatedAt()).append(". DO NOT EDIT.\n");
        out.append("syntax = \"proto3\";\n\n");
        out.append("package ").append(options.protoPackage()).append(";\n\n");
        if (needsWrappers) {
            out.append("import \"google/protobuf/empty.proto\";\n\n");
        }
        out.append("option java_multiple_files = true;\n\n");
        out.append("// kynet wire 契约说明：\n")
                .append("//   STRING action 载荷  -> 裸 UTF-8 字节（非 google.protobuf.StringValue，KynetRawString 仅作文档）\n")
                .append("//   BYTES action 载荷   -> 裸字节\n")
                .append("//   数值 action 载荷    -> KynetPrimitiveValue 信封（kind=序号 + 对应值字段）\n")
                .append("//   List action 载荷    -> KynetListValue 信封\n");

        // 消息与其引用的枚举
        Map<String, String> messageNames = new HashMap<>();
        for (MessageMeta message : model.messages()) {
            messageNames.put(message.javaClass(), message.name());
        }
        Map<String, EnumMeta> enumByName = new HashMap<>();
        for (EnumMeta enumMeta : model.enums()) {
            enumByName.put(enumMeta.javaClass(), enumMeta);
        }

        // 每个 rpc 用到哪些信封
        for (ActionMeta action : model.actions()) {
            collectEnvelope(action.paramType(), envelopeUsage);
            collectEnvelope(action.returnType(), envelopeUsage);
        }

        if (envelopeUsage.contains(TypeKind.STRING) || envelopeUsage.contains(TypeKind.BYTES)
                || envelopeUsage.contains(TypeKind.INT32) || envelopeUsage.contains(TypeKind.INT64)
                || envelopeUsage.contains(TypeKind.BOOL) || envelopeUsage.contains(TypeKind.DOUBLE)
                || envelopeUsage.contains(TypeKind.FLOAT)) {
            out.append("\nmessage KynetPrimitiveValue {\n")
                    .append("  // 0=INT 1=LONG 2=BOOL 3=DOUBLE 4=FLOAT（Java PrimitiveValue.Kind 序号）\n")
                    .append("  int32 kind = 1;\n  int32 int_value = 2;\n  int64 long_value = 3;\n")
                    .append("  bool bool_value = 4;\n  double double_value = 5;\n  float float_value = 6;\n}\n");
            out.append("\nmessage KynetListValue {\n")
                    .append("  // 0=STRING 1=INT 2=LONG 3=BOOL 4=DOUBLE 5=FLOAT 6=MESSAGE（Java ListValue.Kind 序号）\n")
                    .append("  int32 kind = 1;\n  repeated string string_values = 2;\n  repeated int32 int_values = 3;\n")
                    .append("  repeated int64 long_values = 4;\n  repeated bool bool_values = 5;\n")
                    .append("  repeated double double_values = 6;\n  repeated float float_values = 7;\n")
                    .append("  repeated bytes message_values = 8; // 嵌套消息逐条编码，客户端按元素类型解码\n")
                    .append("  string element_type = 9; // MESSAGE 元素的 Java 类名，仅诊断用\n}\n");
        }
        if (envelopeUsage.contains(TypeKind.STRING)) {
            out.append("\n// 仅作文档：实际 wire 是裸 UTF-8 字节\nmessage KynetRawString { string value = 1; }\n");
        }
        if (envelopeUsage.contains(TypeKind.BYTES)) {
            out.append("\n// 仅作文档：实际 wire 是裸字节\nmessage KynetRawBytes { bytes value = 1; }\n");
        }

        for (EnumMeta enumMeta : model.enums()) {
            out.append("\nenum ").append(enumMeta.name()).append(" {\n");
            for (EnumMeta.EnumConstant constant : enumMeta.constants()) {
                out.append("  ").append(constant.name()).append(" = ").append(constant.ordinal()).append(";\n");
            }
            out.append("}\n");
        }

        for (MessageMeta message : model.messages()) {
            out.append("\nmessage ").append(message.name()).append(" {\n");
            for (FieldMeta field : message.fields()) {
                out.append("  ").append(field.repeated() ? "repeated " : "")
                        .append(protoFieldType(field, enumByName, messageNames))
                        .append(' ').append(field.name()).append(" = ").append(field.order()).append(";\n");
            }
            out.append("}\n");
        }

        String currentController = null;
        for (ActionMeta action : model.actions()) {
            if (!action.controllerName().equals(currentController)) {
                if (currentController != null) {
                    out.append("}\n");
                }
                currentController = action.controllerName();
                out.append("\n// ").append(action.controllerClass()).append("\n")
                        .append("service ").append(currentController).append(" {\n");
            }
            out.append("  // cmd=").append(action.cmd()).append(" act=").append(action.act()).append('\n');
            out.append("  rpc ").append(Names.pascal(action.methodName())).append('(')
                    .append(protoActionType(action.paramType(), messageNames))
                    .append(") returns (")
                    .append(action.returnType() == null ? "google.protobuf.Empty"
                            : protoActionType(action.returnType(), messageNames))
                    .append(");\n");
        }
        if (currentController != null) {
            out.append("}\n");
        }

        Files.createDirectories(outDir);
        Path file = outDir.resolve(OUTPUT);
        Files.writeString(file, out.toString());
        return List.of(file);
    }

    private void collectEnvelope(TypeRef ref, Set<TypeKind> usage) {
        if (ref == null) {
            return;
        }
        switch (ref.kind()) {
            case STRING, BYTES, INT32, INT64, BOOL, DOUBLE, FLOAT -> usage.add(ref.kind());
            default -> {
            }
        }
    }

    /** action 载荷级别：STRING/BYTES/数值映射为信封消息，MESSAGE 直用。 */
    private String protoActionType(TypeRef ref, Map<String, String> messageNames) {
        if (ref == null) {
            return "google.protobuf.Empty";
        }
        if (ref.repeated()) {
            return "KynetListValue";
        }
        return switch (ref.kind()) {
            case MESSAGE -> messageNames.getOrDefault(ref.message(), ref.message());
            case STRING -> "KynetRawString";
            case BYTES -> "KynetRawBytes";
            case INT32, INT64, BOOL, DOUBLE, FLOAT -> "KynetPrimitiveValue";
            case ENUM -> "KynetPrimitiveValue";
        };
    }

    /** 消息字段级别：字段号即 order，直接映射 proto 类型。 */
    private String protoFieldType(FieldMeta field, Map<String, EnumMeta> enumByName,
                                  Map<String, String> messageNames) {
        return switch (field.kind()) {
            case MESSAGE -> messageNames.getOrDefault(field.message(), field.message());
            case STRING -> "string";
            case BYTES -> "bytes";
            case INT32 -> "int32";
            case INT64 -> "int64";
            case BOOL -> "bool";
            case DOUBLE -> "double";
            case FLOAT -> "float";
            case ENUM -> enumByName.containsKey(field.enumName())
                    ? enumByName.get(field.enumName()).name() : field.enumName();
        };
    }
}
