package cn.itsub.kynet.codegen.render;

import cn.itsub.kynet.codegen.ir.ActionMeta;
import cn.itsub.kynet.codegen.ir.EnumMeta;
import cn.itsub.kynet.codegen.ir.FieldMeta;
import cn.itsub.kynet.codegen.ir.IrModel;
import cn.itsub.kynet.codegen.ir.MessageMeta;
import cn.itsub.kynet.codegen.ir.TypeKind;
import cn.itsub.kynet.codegen.ir.TypeRef;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * 生成 GDScript 消息编解码（复用 addons/kynet/protobuf.gd 原语）和每个控制器一个静态代理类。
 * 消息用 Dictionary 表达（键 = Java 字段名），await 风格 + 回调风格。
 */
public final class GdScriptRenderer implements Renderer {
    private Map<String, String> messageNames = new LinkedHashMap<>();
    private Map<String, EnumMeta> enumByClass = new LinkedHashMap<>();
    /** javaClass -> GDScript 蛇形键（尾部 _message 剥离，冲突时保留原名）。 */
    private Map<String, String> gdKeys = new LinkedHashMap<>();

    @Override
    public List<Path> render(IrModel model, RenderOptions options, Path outDir) throws IOException {
        messageNames = new LinkedHashMap<>();
        enumByClass = new LinkedHashMap<>();
        gdKeys = new LinkedHashMap<>();
        for (MessageMeta message : model.messages()) {
            messageNames.put(message.javaClass(), message.name());
        }
        for (EnumMeta enumMeta : model.enums()) {
            enumByClass.put(enumMeta.javaClass(), enumMeta);
        }
        assignGdKeys();
        Files.createDirectories(outDir);
        List<Path> written = new ArrayList<>();

        Path messagesFile = outDir.resolve("kynet_messages.gd");
        Files.writeString(messagesFile, messagesFile(model, options));
        written.add(messagesFile);

        Map<String, List<ActionMeta>> byController = new LinkedHashMap<>();
        for (ActionMeta action : model.actions()) {
            byController.computeIfAbsent(action.controllerName(), key -> new ArrayList<>()).add(action);
        }
        for (Map.Entry<String, List<ActionMeta>> entry : byController.entrySet()) {
            Path file = outDir.resolve(Names.snake(entry.getKey()) + ".gd");
            Files.writeString(file, controllerFile(entry.getKey(), entry.getValue(), options));
            written.add(file);
        }
        return written;
    }

    private String header(RenderOptions options) {
        return "## Generated by kynet-codegen at " + options.generatedAt() + ". DO NOT EDIT.\n";
    }

    private void assignGdKeys() {
        // Java 约定消息类多以 Message 结尾（UserMessage -> user），剥离后生成 encode_user_message；
        // 剥离导致重名时保留完整蛇形名。
        Set<String> used = new LinkedHashSet<>();
        List<String> classes = new ArrayList<>(messageNames.keySet());
        classes.sort(String::compareTo);
        for (String javaClass : classes) {
            String full = Names.snake(messageNames.get(javaClass));
            String stripped = full.endsWith("_message") ? full.substring(0, full.length() - "_message".length()) : full;
            if (stripped.isEmpty() || !used.add(stripped)) {
                used.add(full);
                gdKeys.put(javaClass, full);
            } else {
                gdKeys.put(javaClass, stripped);
            }
        }
    }

    private String gdKey(String javaClassOrFqcn) {
        String simple = messageSimple(javaClassOrFqcn);
        return gdKeys.computeIfAbsent(javaClassOrFqcn, key -> Names.snake(simple));
    }

    private String messageEncodeName(String javaClassOrFqcn) {
        return "encode_" + gdKey(javaClassOrFqcn) + "_message";
    }

    private String messageDecodeName(String javaClassOrFqcn) {
        return "decode_" + gdKey(javaClassOrFqcn) + "_message";
    }

    // ---------------- messages ----------------

    private String messagesFile(IrModel model, RenderOptions options) {
        String addon = options.gdAddonPath();
        StringBuilder out = new StringBuilder(header(options))
                .append("class_name KynetGeneratedMessages\nextends RefCounted\n\n")
                .append("const Protobuf = preload(\"").append(addon).append("/protobuf.gd\")\n")
                .append("const PacketCodec = preload(\"").append(addon).append("/packet_codec.gd\")\n\n");

        out.append("""
                # Java PrimitiveValue kinds: INT=0, LONG=1, BOOL=2, DOUBLE=3, FLOAT=4.
                static func encode_string_payload(value: String) -> PackedByteArray:
                	return value.to_utf8_buffer()


                static func decode_string_payload(data: PackedByteArray) -> Dictionary:
                	if not PacketCodec._valid_utf8(data):
                		return {"ok": false}
                	return {"ok": true, "value": data.get_string_from_utf8()}


                static func encode_bytes_payload(value: PackedByteArray) -> PackedByteArray:
                	return value


                static func decode_bytes_payload(data: PackedByteArray) -> Dictionary:
                	return {"ok": true, "value": data}


                static func encode_int_payload(value: int) -> PackedByteArray:
                	return Protobuf.encode_primitive(value, 0)


                static func decode_int_payload(data: PackedByteArray) -> Dictionary:
                	return Protobuf.decode_primitive(data, 0)


                static func encode_long_payload(value: int) -> PackedByteArray:
                	return Protobuf.encode_primitive(value, 1)


                static func decode_long_payload(data: PackedByteArray) -> Dictionary:
                	return Protobuf.decode_primitive(data, 1)


                static func encode_bool_payload(value: bool) -> PackedByteArray:
                	return Protobuf.encode_primitive(value, 2)


                static func decode_bool_payload(data: PackedByteArray) -> Dictionary:
                	return Protobuf.decode_primitive(data, 2)


                static func encode_double_payload(value: float) -> PackedByteArray:
                	return Protobuf.encode_primitive(value, 3)


                static func decode_double_payload(data: PackedByteArray) -> Dictionary:
                	return Protobuf.decode_primitive(data, 3)


                static func encode_float_payload(value: float) -> PackedByteArray:
                	return Protobuf.encode_primitive(value, 4)


                static func decode_float_payload(data: PackedByteArray) -> Dictionary:
                	return Protobuf.decode_primitive(data, 4)


                # Java ListValue kinds: STRING=0, INT=1, LONG=2, BOOL=3, DOUBLE=4, FLOAT=5, MESSAGE=6.
                static func decode_list(data: PackedByteArray, expected_kind: int,
                		element_decoder: Callable = Callable()) -> Dictionary:
                	var decoded := Protobuf.decode_fields(data)
                	if not decoded.ok:
                		return {"ok": false}
                	var fields: Dictionary = decoded.fields
                	var kinds: Array = fields.get(1, [])
                	if kinds.is_empty() or kinds.back().wire != 0 or kinds.back().value != expected_kind:
                		return {"ok": false}
                	var values: Array = []
                	if expected_kind <= 5:
                		for entry in fields.get(expected_kind + 2, []):
                			var value: Variant = entry.value
                			if expected_kind == 0:
                				value = decode_int32(int(value))
                			elif expected_kind == 2:
                				value = value != 0
                			values.append(value)
                	else:
                		for entry in fields.get(8, []):
                			var item: Dictionary = element_decoder.call(entry.value)
                			if not item.get("ok", false):
                				return {"ok": false}
                			values.append(item.value)
                	return {"ok": true, "value": values}


                static func decode_list_string(data: PackedByteArray) -> Dictionary:
                	return decode_list(data, 0)


                static func decode_list_int(data: PackedByteArray) -> Dictionary:
                	return decode_list(data, 1)


                static func decode_list_long(data: PackedByteArray) -> Dictionary:
                	return decode_list(data, 2)


                static func decode_list_bool(data: PackedByteArray) -> Dictionary:
                	return decode_list(data, 3)


                static func decode_list_double(data: PackedByteArray) -> Dictionary:
                	return decode_list(data, 4)


                static func decode_list_float(data: PackedByteArray) -> Dictionary:
                	return decode_list(data, 5)


                # 消息字段解码辅助：非法 UTF-8 返回空串（decode_fields 已保证 wire 合法）。
                static func utf8_or_fail(data: PackedByteArray) -> String:
                	if not PacketCodec._valid_utf8(data):
                		return ""
                	return data.get_string_from_utf8()


                # varint int32 符号还原。
                static func decode_int32(value: int) -> int:
                	var fixed := value & 0xffffffff
                	if fixed >= 0x80000000:
                		fixed -= 0x100000000
                	return fixed


                static func unwrap(result: Dictionary, decoder: String) -> Dictionary:
                	if not result.get("ok", false):
                		return result
                	var session_id: int = result.get("session_id", 0)
                	var user_id: int = result.get("user_id", 0)
                	var payload: Variant = result.get("payload", null)
                	if payload == null or (payload is PackedByteArray and payload.is_empty()):
                		return {"ok": true, "data": null, "session_id": session_id, "user_id": user_id}
                	var decoded: Dictionary = call(decoder, payload)
                	if not decoded.get("ok", false):
                		return {"ok": false, "error_code": "DECODE_FAILED",
                			"error_message": "payload decode failed", "session_id": session_id, "user_id": user_id}
                	return {"ok": true, "data": decoded.get("value"), "session_id": session_id, "user_id": user_id}


                static func log_result(result: Dictionary) -> Dictionary:
                	if result.get("ok", false):
                		print("[Kynet] ok data=", result.get("data"))
                	else:
                		print("[Kynet] error ", result.get("error_code"), " ", result.get("error_message"))
                	return result

                """);

        for (EnumMeta enumMeta : model.enums()) {
            out.append("# Java enum ").append(enumMeta.javaClass()).append(" (wire = ordinal varint)\n")
                    .append("const ").append(enumMeta.name().toUpperCase()).append(" = {");
            List<EnumMeta.EnumConstant> constants = enumMeta.constants();
            for (int i = 0; i < constants.size(); i++) {
                out.append(" \"").append(constants.get(i).name()).append("\": ").append(constants.get(i).ordinal())
                        .append(i + 1 < constants.size() ? "," : "");
            }
            out.append(" }\n\n");
        }

        // 作为 List 元素出现的消息，生成专用的 decode_list_xxx_message 包装
        Set<String> messageListElements = new LinkedHashSet<>();
        for (ActionMeta action : model.actions()) {
            TypeRef ret = action.returnType();
            if (ret != null && ret.repeated() && ret.kind() == TypeKind.MESSAGE) {
                messageListElements.add(ret.message());
            }
        }
        for (String javaClass : messageListElements) {
            out.append("static func decode_list_").append(gdKey(javaClass))
                    .append("_message(data: PackedByteArray) -> Dictionary:\n")
                    .append("\treturn decode_list(data, 6, ").append(messageDecodeName(javaClass)).append(")\n\n\n");
        }

        for (MessageMeta message : model.messages()) {
            out.append(encodeMessage(message)).append(decodeMessage(message));
        }
        return out.toString();
    }

    private String encodeMessage(MessageMeta message) {
        StringBuilder out = new StringBuilder("## Java ").append(message.javaClass()).append('\n')
                .append("static func ").append(messageEncodeName(message.javaClass()))
                .append("(message: Dictionary) -> PackedByteArray:\n")
                .append("\tvar output := PackedByteArray()\n");
        for (FieldMeta field : message.fields()) {
            String get = "message.get(\"" + field.name() + "\"";
            if (field.repeated()) {
                out.append("\tfor item in ").append(get).append(", []):\n")
                        .append("\t\toutput.append_array(")
                        .append(encodeFieldExpression(field, "item")).append(")\n");
            } else if (field.kind() == TypeKind.MESSAGE) {
                out.append("\tif ").append(get).append(", null) != null:\n")
                        .append("\t\toutput.append_array(")
                        .append(encodeFieldExpression(field, "message.get(\"" + field.name() + "\")")).append(")\n");
            } else {
                out.append("\toutput.append_array(")
                        .append(encodeFieldExpression(field, fieldDefaultedAccess(field))).append(")\n");
            }
        }
        out.append("\treturn output\n\n\n");
        return out.toString();
    }

    /** 非消息字段的容错访问：缺键时给默认值，避免 Dictionary 下标报错。 */
    private String fieldDefaultedAccess(FieldMeta field) {
        return "message.get(\"" + field.name() + "\", " + defaultValue(field) + ")";
    }

    private String encodeFieldExpression(FieldMeta field, String value) {
        long number = field.order();
        return switch (field.kind()) {
            case STRING -> "Protobuf.string_field(" + number + ", " + value + ")";
            case BYTES -> "Protobuf.bytes_field(" + number + ", " + value + ")";
            case INT32, INT64, ENUM -> "Protobuf.varint_field(" + number + ", int(" + value + "))";
            case BOOL -> "Protobuf.varint_field(" + number + ", 1 if " + value + " else 0)";
            case DOUBLE -> "Protobuf.float_field(" + number + ", " + value + ", true)";
            case FLOAT -> "Protobuf.float_field(" + number + ", " + value + ", false)";
            case MESSAGE -> messageEncodeName(field.message()) + "(" + value + ")";
        };
    }

    private String decodeMessage(MessageMeta message) {
        StringBuilder out = new StringBuilder("static func ").append(messageDecodeName(message.javaClass()))
                .append("(data: PackedByteArray) -> Dictionary:\n")
                .append("\tvar decoded := Protobuf.decode_fields(data)\n")
                .append("\tif not decoded.ok:\n\t\treturn {\"ok\": false}\n")
                .append("\tvar fields: Dictionary = decoded.fields\n")
                .append("\tvar message := {");
        List<FieldMeta> fields = message.fields();
        if (fields.isEmpty()) {
            out.append("}\n\treturn {\"ok\": true, \"value\": message}\n\n\n");
            return out.toString();
        }
        for (int i = 0; i < fields.size(); i++) {
            out.append(" \"").append(fields.get(i).name()).append("\": ").append(defaultValue(fields.get(i)))
                    .append(i + 1 < fields.size() ? "," : "");
        }
        out.append(" }\n");
        for (FieldMeta field : fields) {
            out.append(decodeFieldStatement(field));
        }
        out.append("\treturn {\"ok\": true, \"value\": message}\n\n\n");
        return out.toString();
    }

    private String defaultValue(FieldMeta field) {
        if (field.repeated()) {
            return "[]";
        }
        return switch (field.kind()) {
            case STRING -> "\"\"";
            case BYTES -> "PackedByteArray()";
            case MESSAGE -> "null";
            case INT32, INT64, ENUM -> "0";
            case BOOL -> "false";
            case DOUBLE, FLOAT -> "0.0";
        };
    }

    private String decodeFieldStatement(FieldMeta field) {
        String name = field.name();
        StringBuilder out = new StringBuilder("\tvar entries_").append(name)
                .append(": Array = fields.get(").append(field.order()).append(", [])\n");
        if (field.repeated()) {
            out.append("\tfor entry in entries_").append(name).append(":\n");
            if (field.kind() == TypeKind.MESSAGE) {
                out.append("\t\tvar sub_").append(name).append(": Dictionary = ")
                        .append(messageDecodeName(field.message())).append("(entry.value)\n")
                        .append("\t\tmessage[\"").append(name).append("\"].append(")
                        .append("(sub_").append(name).append(".get(\"value\") if sub_").append(name)
                        .append(".get(\"ok\", false) else null))\n");
            } else {
                out.append("\t\tmessage[\"").append(name).append("\"].append(")
                        .append(scalarDecodeExpression(field, "entry.value")).append(")\n");
            }
            return out.toString();
        }
        out.append("\tif not entries_").append(name).append(".is_empty():\n");
        if (field.kind() == TypeKind.MESSAGE) {
            out.append("\t\tvar sub_").append(name).append(": Dictionary = ")
                    .append(messageDecodeName(field.message())).append("(entries_").append(name).append(".back().value)\n")
                    .append("\t\tmessage[\"").append(name).append("\"] = ")
                    .append("(sub_").append(name).append(".get(\"value\") if sub_").append(name)
                    .append(".get(\"ok\", false) else null)\n");
        } else {
            out.append("\t\tmessage[\"").append(name).append("\"] = ")
                    .append(scalarDecodeExpression(field, "entries_" + name + ".back().value")).append('\n');
        }
        return out.toString();
    }

    private String scalarDecodeExpression(FieldMeta field, String rawValue) {
        return switch (field.kind()) {
            case STRING -> "utf8_or_fail(" + rawValue + ")";
            case BYTES -> rawValue;
            case INT32, ENUM -> "decode_int32(int(" + rawValue + "))";
            case INT64 -> "int(" + rawValue + ")";
            case BOOL -> "(" + rawValue + " != 0)";
            case DOUBLE, FLOAT -> "float(" + rawValue + ")";
            default -> throw new IllegalStateException("非标量字段走 MESSAGE 分支");
        };
    }

    // ---------------- controller ----------------

    private String controllerFile(String controller, List<ActionMeta> actions, RenderOptions options) {
        String generatedPath = options.gdGeneratedPath();
        StringBuilder out = new StringBuilder(header(options))
                .append("class_name ").append(controller).append("\nextends RefCounted\n\n")
                .append("const Messages = preload(\"").append(generatedPath).append("/kynet_messages.gd\")\n\n\n");
        for (ActionMeta action : actions) {
            out.append(controllerAction(action));
        }
        return out.toString();
    }

    private static final Set<String> GD_BUILTIN_NAMES = Set.of(
            "string", "int", "float", "double", "bool", "bytes", "long", "name", "self", "range", "type", "id");

    /** GDScript 内置类型名做参数名时加 param_ 前缀，避免 shadow 警告。 */
    private String gdParamName(String name) {
        if (name == null || name.isEmpty()) {
            return name;
        }
        String snake = Names.snake(name);
        return GD_BUILTIN_NAMES.contains(snake) ? "param_" + snake : snake;
    }

    private String controllerAction(ActionMeta action) {
        String of = "of_" + Names.snake(action.methodName());
        String ofAwait = "of_await_" + Names.snake(action.methodName());
        String paramName = action.paramName() == null ? "" : gdParamName(action.paramName());
        String withParam = paramName.isEmpty() ? ""
                : ", " + paramName + ": " + (action.paramType() == null ? "Variant" : gdParamType(action.paramType()));
        String passParam = paramName.isEmpty() ? "" : ", " + paramName;
        String encodeCall = paramName.isEmpty() ? "null"
                : "Messages." + payloadEncoder(action.paramType()) + "(" + paramName + ")";
        String decoder = payloadDecoder(action.returnType());

        return "## cmd=" + action.cmd() + " act=" + action.act()
                + " 回调风格：" + of + "(client" + (paramName.isEmpty() ? "" : ", " + paramName)
                + ", func(result): Messages.log_result(result))\n"
                + "static func " + of + "(client" + withParam + ", callback: Callable) -> void:\n"
                + "\tvar result: Dictionary = await " + ofAwait + "(client" + passParam + ")\n"
                + "\tcallback.call(result)\n\n\n"
                + "## cmd=" + action.cmd() + " act=" + action.act()
                + " await 风格：var result := await " + ofAwait + "(client"
                + (paramName.isEmpty() ? "" : ", " + paramName) + ")\n"
                + "static func " + ofAwait + "(client" + withParam + ") -> Dictionary:\n"
                + "\tvar result: Dictionary = await client.request_async(" + action.cmd() + ", " + action.act()
                + ", " + encodeCall + ")\n"
                + "\treturn Messages.unwrap(result, \"" + decoder + "\")\n\n\n";
    }

    private String gdParamType(TypeRef ref) {
        if (ref.repeated()) {
            return "Array";
        }
        return switch (ref.kind()) {
            case MESSAGE -> "Dictionary";
            case STRING -> "String";
            case BYTES -> "PackedByteArray";
            case INT32, INT64 -> "int";
            case BOOL -> "bool";
            case DOUBLE, FLOAT -> "float";
            case ENUM -> "int";
        };
    }

    private String payloadEncoder(TypeRef ref) {
        if (ref == null) {
            throw new IllegalStateException("无载荷时不应调用 payloadEncoder");
        }
        return switch (ref.kind()) {
            case MESSAGE -> messageEncodeName(ref.message());
            case STRING -> "encode_string_payload";
            case BYTES -> "encode_bytes_payload";
            case INT32 -> "encode_int_payload";
            case INT64 -> "encode_long_payload";
            case BOOL -> "encode_bool_payload";
            case DOUBLE -> "encode_double_payload";
            case FLOAT -> "encode_float_payload";
            case ENUM -> "encode_int_payload";
        };
    }

    private String payloadDecoder(TypeRef ref) {
        if (ref == null) {
            return "decode_bytes_payload";
        }
        if (ref.repeated()) {
            return switch (ref.kind()) {
                case STRING -> "decode_list_string";
                case INT32 -> "decode_list_int";
                case INT64 -> "decode_list_long";
                case BOOL -> "decode_list_bool";
                case DOUBLE -> "decode_list_double";
                case FLOAT -> "decode_list_float";
                case MESSAGE -> "decode_list_" + gdKey(ref.message()) + "_message";
                default -> throw new IllegalStateException("ENUM 列表未支持");
            };
        }
        return switch (ref.kind()) {
            case MESSAGE -> messageDecodeName(ref.message());
            case STRING -> "decode_string_payload";
            case BYTES -> "decode_bytes_payload";
            case INT32 -> "decode_int_payload";
            case INT64 -> "decode_long_payload";
            case BOOL -> "decode_bool_payload";
            case DOUBLE -> "decode_double_payload";
            case FLOAT -> "decode_float_payload";
            case ENUM -> "decode_int_payload";
        };
    }

    private String messageSimple(String fqcn) {
        return messageNames.getOrDefault(fqcn, Names.pascal(simpleName(fqcn)));
    }

    private String simpleName(String fqcn) {
        int dot = fqcn.lastIndexOf('.');
        return dot > 0 ? fqcn.substring(dot + 1) : fqcn;
    }
}
